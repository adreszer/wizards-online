"""Server-side copies of generated castle data (nakama/modules/*.lua)."""


def area_map(plan, path):
    """world_areas.lua: area id -> {kind, house}, so the match handler can validate
    classroom-only actions without trusting the client."""
    lines = ["-- GENERATED by tools/generate_castle.py; do not edit. area id -> { kind, house }",
             "return {"]
    for r in sorted(plan.rooms.values(), key=lambda r: r.id):
        lines.append(f'  ["{r.id}"] = {{ kind = "{r.kind}", house = {r.house} }},')
    lines.append("}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
