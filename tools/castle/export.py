"""Server-side copies of generated castle data (nakama/modules/*.lua)."""


def area_map(plan, path):
    """world_areas.lua: area id -> {kind, house, c, s}, so the match handler can validate
    classroom-only actions without trusting the client, and check a reported area against
    the player's position (c: the zone box's centre, s: its size, as in the AreaZone)."""
    from .build import zone_box
    lines = ["-- GENERATED by tools/generate_castle.py; do not edit. area id -> { kind, house, c = centre, s = size }",
             "return {"]
    for r in sorted(plan.rooms.values(), key=lambda r: r.id):
        cx, y, cz, w, h, d = zone_box(r)
        lines.append(f'  ["{r.id}"] = {{ kind = "{r.kind}", house = {r.house}, c = {{ {cx:g}, {y:g}, {cz:g} }}, s = {{ {w:g}, {h:g}, {d:g} }} }},')
    lines.append("}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
